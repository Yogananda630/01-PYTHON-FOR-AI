"""
Python Data Types
-----------------
Fundamental data types used in Python and AI Engineering.
"""

# 1. Integer
age = 21
samples = 1000

print("Integer:")
print(age)
print(type(age))


# 2. Float
accuracy = 95.5
learning_rate = 0.001

print("\nFloat:")
print(accuracy)
print(type(accuracy))


# 3. String
name = "Yogananda"
model_name = "AI Model"

print("\nString:")
print(name)
print(type(name))


# 4. Boolean
is_training = True
is_completed = False

print("\nBoolean:")
print(is_training)
print(type(is_training))


# 5. List
features = ["age", "salary", "experience"]

print("\nList:")
print(features)
print(type(features))


# 6. Tuple
coordinates = (10.5, 20.5)

print("\nTuple:")
print(coordinates)
print(type(coordinates))


# 7. Set
unique_labels = {"cat", "dog", "bird"}

print("\nSet:")
print(unique_labels)
print(type(unique_labels))


# 8. Dictionary
model = {
    "name": "Neural Network",
    "accuracy": 95.5,
    "epochs": 10
}

print("\nDictionary:")
print(model)
print(type(model))


# 9. None
prediction = None

print("\nNone:")
print(prediction)
print(type(prediction))


